// Small writing helpers so every topic looks the same.

const p = (text) => `<p>${text}</p>`;
const h = (text) => `<h3>${text}</h3>`;
const list = (items) => `<ul class="g-list">${items.map((item) => `<li>${item}</li>`).join("")}</ul>`;
const steps = (items) => `<ol class="g-steps">${items.map((item) => `<li>${item}</li>`).join("")}</ol>`;
const go = (href, label) => `<a class="g-go" href="${href}">${label} <span aria-hidden="true">→</span></a>`;
const goes = (...links) => `<div class="g-goes">${links.join("")}</div>`;
const see = (id, label) => `<a class="g-link" href="#guide/${id}">${label}</a>`;
const tip = (text) => `<div class="g-callout tip"><strong>Tip</strong><div>${text}</div></div>`;
const note = (text) => `<div class="g-callout note"><strong>Good to know</strong><div>${text}</div></div>`;
const warn = (text) => `<div class="g-callout warn"><strong>Careful</strong><div>${text}</div></div>`;
const cmd = (command, what = "") => `<div class="g-cmd"><code>${esc(command)}</code><button type="button" class="g-copy" data-copy="${esc(command)}" title="Copy to clipboard">Copy</button>${what ? `<span class="g-cmd-what">${what}</span>` : ""}</div>`;
const example = (title, lines) => `<div class="g-example"><div class="g-example-title">Example: ${title}</div>${lines.join("")}</div>`;
const table = (heads, rows) => `<div class="table-wrap"><table class="g-table"><thead><tr>${heads.map((head) => `<th>${head}</th>`).join("")}</tr></thead><tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td>${cell}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
const chip = (state, label) => `<span class="g-chip" style="--chip: var(--st-${state})">${label}</span>`;

